#!/usr/bin/env node
/**
 * Copies Smithy build output into the pnpm workspace packages and rewrites the
 * generated package.json files so they build with plain `tsc` (no yarn/concurrently).
 *
 * Usage: node spec/scripts/sync-generated.mjs   (run after `smithy build` in spec/)
 */
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const build = resolve(root, 'spec', 'build', 'smithy', 'source');

const targets = [
  { from: 'typescript-server-codegen', to: 'packages/api-server-sdk', kind: 'ts' },
  { from: 'openapi', to: 'packages/openapi', kind: 'openapi' },
];

const HEADER = `<!-- GENERATED FILE. Regenerate with \`pnpm codegen\` (see spec/README.md). Do not edit by hand. -->\n`;

for (const t of targets) {
  const src = join(build, t.from);
  const dest = join(root, t.to);
  if (!existsSync(src)) {
    console.error(`missing build output: ${src} (run \`smithy build\` in spec/ first)`);
    process.exit(1);
  }
  mkdirSync(dest, { recursive: true });

  if (t.kind === 'ts') {
    rmSync(join(dest, 'src'), { recursive: true, force: true });
    cpSync(join(src, 'src'), join(dest, 'src'), { recursive: true });
    for (const f of [
      'tsconfig.json',
      'tsconfig.cjs.json',
      'tsconfig.es.json',
      'tsconfig.types.json',
    ]) {
      cpSync(join(src, f), join(dest, f));
    }
    const pkg = JSON.parse(readFileSync(join(src, 'package.json'), 'utf8'));
    pkg.scripts = {
      build: 'tsc -p tsconfig.cjs.json && tsc -p tsconfig.es.json && tsc -p tsconfig.types.json',
      clean: 'rm -rf dist-cjs dist-es dist-types tsconfig.*.tsbuildinfo',
    };
    delete pkg.typesVersions;
    pkg.devDependencies = {
      '@tsconfig/node20': pkg.devDependencies?.['@tsconfig/node20'] ?? '20.1.8',
      '@types/node': '^24.2.0',
      typescript: '^5.9.2',
    };
    pkg.files = ['dist-*/**', 'src/**'];
    writeFileSync(join(dest, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');
    writeFileSync(
      join(dest, 'README.md'),
      `${HEADER}\n# ${pkg.name}\n\nGenerated by the Smithy \`${t.from}\` plugin from \`spec/model\`.\n\n- \`src/\` is generated code and is committed so nobody needs a JDK to run the project.\n- Build output (\`dist-*\`) is produced by \`pnpm build\` in this package and is git-ignored.\n- Regenerate with \`pnpm codegen\` at the repo root.\n`,
    );
  } else {
    const spec = JSON.parse(readFileSync(join(src, 'SupportAssistant.openapi.json'), 'utf8'));
    writeFileSync(join(dest, 'openapi.json'), JSON.stringify(spec, null, 2) + '\n');
    writeFileSync(
      join(dest, 'package.json'),
      JSON.stringify(
        {
          name: '@app/openapi',
          version: '0.1.0',
          private: true,
          description: 'OpenAPI 3.1 document generated from the Smithy model',
          type: 'module',
          exports: { './openapi.json': './openapi.json' },
          files: ['openapi.json'],
        },
        null,
        2,
      ) + '\n',
    );
    writeFileSync(
      join(dest, 'README.md'),
      `${HEADER}\n# @app/openapi\n\n\`openapi.json\` is generated by the Smithy \`openapi\` plugin from \`spec/model\`. The api serves it at \`/api/docs\` (Swagger UI) and \`/api/openapi.json\`.\n\nRegenerate with \`pnpm codegen\` at the repo root.\n`,
    );
  }
  console.log(`synced ${t.from} -> ${t.to}`);
}
